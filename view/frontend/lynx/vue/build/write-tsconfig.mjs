#!/usr/bin/env node
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { relative, resolve } from 'node:path'
import { resolveSourceDirs } from './config-kit.js'
import { readDependencyNames } from './theme-fallback.js'

// Writes tsconfig.modules.json for `vue-tsc` from the bundler's own source dirs: the theme, its parent themes and
// every module in the build, in fallback order. Generated per type-check, never committed.

// The theme this runs for: npm runs a script in the build root whose package.json holds it.
const here = process.cwd()

/** A path as this tsconfig has to spell it: relative to the file, forward slashes. */
const asPath = absolute => {
    const rel = relative(here, absolute).replace(/\\/g, '/')
    return rel.startsWith('.') ? rel : './' + rel
}

// Index 0 is the theme's own src, already covered by `@/*` and the src/ globs
const [, ...dirs] = resolveSourceDirs(here)

// Per module: the building theme's override, the parent themes' overrides, then its source
const modules = {}
for (const { dir, prefix } of dirs) {
    if (prefix) (modules[prefix] ??= []).push(asPath(dir) + '/*')
}

const paths = { '@/*': ['./src/*'] }
for (const prefix of Object.keys(modules).sort()) paths[`${prefix}/*`] = modules[prefix]

// npm imports resolve in this build root's node_modules, from the modules under vendor/ too. A path mapping skips
// a package's `exports`, so each subpath it exports with types ('@inertiajs/vue3/server') is mapped by hand.
for (const name of readDependencyNames(here)) {
    const manifest = resolve(here, 'node_modules', name, 'package.json')
    if (!existsSync(manifest)) continue
    for (const [subpath, target] of Object.entries(JSON.parse(readFileSync(manifest, 'utf8')).exports ?? {})) {
        const types = typeof target === 'object' && target !== null ? (target.types ?? target.import?.types) : null
        if (subpath.startsWith('./') && !subpath.includes('*') && typeof types === 'string') {
            paths[`${name}/${subpath.slice(2)}`] = [asPath(resolve(here, 'node_modules', name, types))]
        }
    }
}
paths['*'] = ['./node_modules/@types/*', './node_modules/*']

const include = [
    // Component props from etc/components/*.graphqls, written by bin/magento lynx:static:deploy
    'dist/props.d.ts',
    'src/**/*.ts',
    'src/**/*.d.ts',
    'src/**/*.vue',
    ...dirs.flatMap(({ dir }) => ['vue', 'ts'].map(ext => `${asPath(dir)}/**/*.${ext}`)),
]

const body = {
    extends: './tsconfig.json',
    compilerOptions: { paths },
    include,
}

writeFileSync(
    resolve(here, 'tsconfig.modules.json'),
    '// Generated by lynx-tsconfig-vue — do not edit; run `npm run type-check`.\n' +
        JSON.stringify(body, null, 2) +
        '\n'
)

// Only with bin/magento lynx:static:deploy -v
if (process.env.LYNX_BUILD_VERBOSE) {
    console.log(
        `[lynx] tsconfig.modules.json: ${Object.keys(modules).length} modules, ${Object.keys(paths).length} path entries`
    )
}
